#!/usr/bin/env python3
"""Generate every sample file in samples/, plus manifest.json (expected outcomes), the sample definitions
(JSON and SQL), samples/.gitignore (large files) and the README catalog.

    python samples/tools/generate_samples.py                 # everything (several minutes, ~1 GB)
    python samples/tools/generate_samples.py --skip-large    # everything except 05-large/
    python samples/tools/generate_samples.py --skip-max-rows # skip the 1,048,575-row workbook

Requires: pip install xlsxwriter xlwt
Output is deterministic (fixed random seed).
"""
import argparse
import json
import shutil
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

from samplegen import examples_and_handling, large, sheet_tables, single_table  # noqa: E402
from samplegen.definitions import DEFINITIONS, definitions_json, definitions_sql  # noqa: E402
from samplegen.readme import render_readme  # noqa: E402
from samplegen.writers import MANIFEST, ROOT  # noqa: E402

GENERATED_DIRS = ['01-single-table', '02-sheet-tables', '03-example-files', '04-file-handling']
LARGE_DIR = '05-large'
GIT_IGNORE_BYTES = 10 * 1024 * 1024


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('--skip-large', action='store_true', help='do not (re)generate 05-large/')
    parser.add_argument('--skip-max-rows', action='store_true', help='skip the Excel max-rows workbook')
    args = parser.parse_args()

    dirs = GENERATED_DIRS + ([] if args.skip_large else [LARGE_DIR])
    for name in dirs:
        shutil.rmtree(ROOT / name, ignore_errors=True)

    single_table.build()
    sheet_tables.build()
    examples_and_handling.build()
    if not args.skip_large:
        print('Generating large files (this takes a few minutes)...', flush=True)
        large.build(include_max_rows=not args.skip_max_rows)
    else:
        previous = ROOT / 'manifest.json'
        if previous.exists():
            MANIFEST.extend(e for e in json.loads(previous.read_text(encoding='utf-8'))['files'] if e['file'].startswith(LARGE_DIR + '/'))

    for entry in MANIFEST:
        path = ROOT / entry['file']
        entry['sizeBytes'] = path.stat().st_size if path.exists() else None

    definitions_dir = ROOT / 'definitions'
    definitions_dir.mkdir(exist_ok=True)
    (definitions_dir / 'sample_definitions.json').write_text(json.dumps(definitions_json(), indent=2, ensure_ascii=False) + '\n', encoding='utf-8')
    (definitions_dir / 'sample_definitions.sql').write_text(definitions_sql(), encoding='utf-8')
    (ROOT / 'manifest.json').write_text(json.dumps({
        'generatedBy': 'samples/tools/generate_samples.py',
        'uploadLimitBytes': large.UPLOAD_LIMIT,
        'files': MANIFEST,
    }, indent=2, ensure_ascii=False) + '\n', encoding='utf-8')

    big = sorted(e['file'] for e in MANIFEST if (e.get('sizeBytes') or 0) > GIT_IGNORE_BYTES)
    (ROOT / '.gitignore').write_text(
        '# GENERATED by tools/generate_samples.py: files over 10 MB are regenerated on demand instead of committed.\n'
        '__pycache__/\n' + ''.join(f'/{name}\n' for name in big), encoding='utf-8')
    (ROOT / 'README.md').write_text(render_readme(MANIFEST, DEFINITIONS), encoding='utf-8')

    total = sum(e.get('sizeBytes') or 0 for e in MANIFEST)
    print(f'Generated {len(MANIFEST)} sample files ({total / 1024 / 1024:,.1f} MB); {len(big)} git-ignored as large.')


if __name__ == '__main__':
    main()
